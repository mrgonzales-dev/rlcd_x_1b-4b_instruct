# ── helpers ───────────────────────────────────────────────────────────────
def new_page(title):
    fig = plt.figure(figsize=(11.69, 8.27))  # A4 landscape
    fig.suptitle(title, fontsize=16, fontweight="bold", x=0.05, ha="left", y=0.96)
    fig.text(0.05, 0.02, "laya tool-call routing benchmark - english checkpoint - CPU - generated by benchmark_report.py",
             fontsize=7, color="gray")
    return fig

def text_page(pdf, title, blocks):
    fig = new_page(title)
    ax = fig.add_axes([0, 0, 1, 1]); ax.axis("off")
    y = 0.88
    for head, body in blocks:
        ax.text(0.05, y, head, fontsize=12, fontweight="bold", va="top")
        y -= 0.035
        lines = [w for raw in body.split("\n") for w in (textwrap.wrap(raw, 118) or [""])] \
            if isinstance(body, str) else body
        for line in lines:
            ax.text(0.06, y, line, fontsize=10, va="top", family="monospace" if line.startswith(" ") else "sans-serif")
            y -= 0.026
        y -= 0.02
    pdf.savefig(fig); plt.close(fig)

def box(ax, xy, w, h, text, fc="#dbeafe", ec="#1e40af"):
    x, y = xy
    ax.add_patch(FancyBboxPatch((x, y), w, h, boxstyle="round,pad=0.012",
                                fc=fc, ec=ec, lw=1.4))
    ax.text(x + w / 2, y + h / 2, text, ha="center", va="center", fontsize=9.5)

def arrow(ax, p1, p2, label=""):
    ax.add_patch(FancyArrowPatch(p1, p2, arrowstyle="-|>", mutation_scale=16,
                                 lw=1.4, color="#334155"))
    if label:
        ax.text((p1[0] + p2[0]) / 2, (p1[1] + p2[1]) / 2 + 0.035, label,
                ha="center", fontsize=8.5, color="#334155", style="italic")

