         "  - Production rule: plan = argmax(choice) - {none}  UNION  {t: any noul phrasing > 0.5}.\n"
         "  - Execute the plan in fixed dependency order (gather -> compute -> send); don't ask laya to order.\n"
         "  - Dict/JSON states degrade answers vs plain strings (0.72 -> 0.29 on the same message) - keep "
